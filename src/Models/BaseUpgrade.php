namespace Blackcube\Dcore\Models;

use Blackcube\Dcore\Traits\ModelKindTrait;
use Yiisoft\ActiveRecord\ActiveRecord;
use Yiisoft\ActiveRecord\Trait\EventsTrait;
use Yiisoft\ActiveRecord\Trait\MagicPropertiesTrait;

/**
 * BaseUpgrade - Pure Yii3 ActiveRecord base class.
 * Contains: properties only, no relations.
 *
 * @copyright 2010-2026 Blackcube - Philippe Gaultier
 * @license https://www.blackcube.io/license
 * @link https://www.blackcube.io
 */
abstract class BaseUpgrade extends ActiveRecord
{
    use MagicPropertiesTrait;
    use EventsTrait;
    use ModelKindTrait;

    abstract protected function fqcn(string $fqcn): string;

    protected string $name;
    protected int $applyTime = 0;

    public function tableName(): string
    {
        return '{{%upgrades}}';
    }

    public function getName(): ?string
    {
        return $this->name ?? null;
    }

    public function setName(string $name): void
    {
        $this->name = $name;
    }

    public function getApplyTime(): int
    {
        return $this->applyTime;
    }

    public function setApplyTime(int $applyTime): void
    {
        $this->applyTime = $applyTime;
    }
}
